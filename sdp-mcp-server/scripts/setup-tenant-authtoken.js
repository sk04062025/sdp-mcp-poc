#!/usr/bin/env node

/**
 * Setup Tenant with AuthToken Script
 * 
 * This script registers a tenant with a static AuthToken for on-premise SDP instances.
 * It handles the necessary encryption to match the server's expected format.
 */

const { Client } = require('pg');
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const readline = require('readline');

// --- Encryption Logic (Matched to src/auth/encryption.ts) ---

const DEFAULT_CONFIG = {
  algorithm: 'aes-256-gcm',
  keyLength: 32,
  saltLength: 32,
  tagLength: 16,
  ivLength: 16,
  iterations: 100000,
};

function deriveKey(masterKey, tenantId, salt) {
  const context = Buffer.concat([
    Buffer.from(tenantId),
    Buffer.from('sdp-mcp-encryption'),
  ]);
  
  return crypto.pbkdf2Sync(
    masterKey,
    Buffer.concat([salt, context]),
    DEFAULT_CONFIG.iterations,
    DEFAULT_CONFIG.keyLength,
    'sha256'
  );
}

function encrypt(data, masterKey, tenantId) {
  const salt = crypto.randomBytes(DEFAULT_CONFIG.saltLength);
  const iv = crypto.randomBytes(DEFAULT_CONFIG.ivLength);
  
  // Ensure masterKey is correct length buffer
  const masterKeyBuffer = Buffer.from(masterKey.substring(0, 32));
  
  const key = deriveKey(masterKeyBuffer, tenantId, salt);
  
  const cipher = crypto.createCipheriv(DEFAULT_CONFIG.algorithm, key, iv);
  
  const encrypted = Buffer.concat([
    cipher.update(data, 'utf8'),
    cipher.final(),
  ]);
  
  const tag = cipher.getAuthTag();
  
  // Format: version:salt:iv:tag:encrypted
  const version = 1;
  return `${version}:${salt.toString('base64')}:${iv.toString('base64')}:${tag.toString('base64')}:${encrypted.toString('base64')}`;
}

// --- Main Script ---

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

const question = (query) => new Promise((resolve) => rl.question(query, resolve));

async function main() {
  console.log('🔧 Setup Tenant with AuthToken');
  console.log('============================\n');

  // 1. Load Environment Variables
  const envPath = path.join(__dirname, '..', '.env');
  if (!fs.existsSync(envPath)) {
    console.error('❌ .env file not found. Please copy .env.example to .env and configure it first.');
    process.exit(1);
  }

  const envContent = fs.readFileSync(envPath, 'utf8');
  const env = {};
  envContent.split('\n').forEach(line => {
    const match = line.match(/^([^#=]+)=(.*)$/);
    if (match) {
      env[match[1].trim()] = match[2].trim();
    }
  });

  const dbConfig = {
    user: env.DB_USER || 'sdpmcpservice',
    host: env.DB_HOST || 'localhost',
    database: env.DB_NAME || 'sdp_mcp',
    password: env.DB_PASSWORD,
    port: parseInt(env.DB_PORT || '5432'),
  };

  if (!env.ENCRYPTION_KEY) {
    console.error('❌ ENCRYPTION_KEY not found in .env');
    process.exit(1);
  }

  // 2. Gather Inputs
  console.log('Please provide the following details:');
  
  let tenantName = await question('Tenant Name (e.g., "Default"): ');
  if (!tenantName) tenantName = 'Default';
  
  let sdpUrl = await question('SDP Base URL (e.g., "http://sdp-server:8080"): ');
  while (!sdpUrl) {
    sdpUrl = await question('SDP Base URL is required: ');
  }
  // Remove trailing details if user pasted full API url
  try {
    const urlObj = new URL(sdpUrl);
    sdpUrl = urlObj.origin;
    console.log(`Using Base URL: ${sdpUrl}`);
  } catch (e) {
    console.warn('Warning: Invalid URL format');
  }

  let authToken = await question('AuthToken: ');
  while (!authToken) {
    authToken = await question('AuthToken is required: ');
  }

  const dataCenter = 'US'; // Default for on-premise, not strictly used but required by schema enum typically

  console.log('\nProcessing...');

  // 3. Database Operations
  const client = new Client(dbConfig);

  try {
    await client.connect();
    
    // Start Transaction
    await client.query('BEGIN');

    // A. Create/Get Tenant
    // Check if exists first to avoid duplicate key error if we want to support updating (or just fail)
    // For this script, let's try to insert, if conflict, get the ID.
    
    // We need a unique ID for the encryption context.
    // If tenant exists, we use its ID. If not, the DB generates one (UUID).
    // To properly handle the chicken-egg problem of needing ID for encryption before insertion if we were generating ID client side:
    // But here ID is generated by DB (usually). Let's check schema.
    // Tenant repository used `INSERT ... RETURNING *`.
    
    // Let's check if tenant exists by name
    let tenantId;
    const existingTenantRes = await client.query('SELECT id FROM tenants WHERE name = $1', [tenantName]);
    
    if (existingTenantRes.rows.length > 0) {
      tenantId = existingTenantRes.rows[0].id;
      console.log(`ℹ️  Tenant '${tenantName}' already exists (ID: ${tenantId}). Updating configuration...`);
    } else {
      // Create new tenant
      const insertTenantRes = await client.query(
        `INSERT INTO tenants (name, data_center, status, rate_limit_tier, metadata)
         VALUES ($1, $2, 'active', 'standard', '{}')
         RETURNING id`,
        [tenantName, dataCenter]
      );
      tenantId = insertTenantRes.rows[0].id;
      console.log(`✅ Tenant '${tenantName}' created (ID: ${tenantId}).`);
    }

    // B. Encrypt AuthToken
    // Now we have tenantId, we can encrypt.
    const encryptedAuthToken = encrypt(authToken, env.ENCRYPTION_KEY, tenantId);
    
    // Dummy values for OAuth fields as they are required or we just null them if allowed?
    // Looking at schema from repository, most encrypted fields seem to be nullable in the model, 
    // but let's check the table definition if we could. 
    // Assuming we can pass null for client_id/secret if on-premise/authtoken mode is used?
    // Actually, `src/tenants/manager.ts` creates with OAuth config.
    // Let's encrypt dummy values for client_id/secret just in case constraints exist.
    const dummyEncrypted = encrypt('dummy', env.ENCRYPTION_KEY, tenantId);

    // C. Upsert OAuth Config
    // Check if config exists
    const existingConfigRes = await client.query('SELECT id FROM oauth_configs WHERE tenant_id = $1', [tenantId]);
    
    if (existingConfigRes.rows.length > 0) {
      await client.query(
        `UPDATE oauth_configs 
         SET auth_token_encrypted = $1, 
             sdp_instance_url = $2,
             updated_at = NOW()
         WHERE tenant_id = $3`,
        [encryptedAuthToken, sdpUrl, tenantId]
      );
      console.log('✅ Configuration updated with AuthToken.');
    } else {
      await client.query(
        `INSERT INTO oauth_configs (
           tenant_id, 
           client_id_encrypted, 
           client_secret_encrypted, 
           auth_token_encrypted, 
           sdp_instance_url,
           allowed_scopes
         )
         VALUES ($1, $2, $3, $4, $5, $6)`,
        [
          tenantId, 
          dummyEncrypted, // clientId
          dummyEncrypted, // clientSecret
          encryptedAuthToken, 
          sdpUrl,
          [] // empty scopes array
        ]
      );
      console.log('✅ Configuration created with AuthToken.');
    }

    await client.query('COMMIT');
    console.log('\n🎉 Setup complete! You can now start the server.');

  } catch (err) {
    await client.query('ROLLBACK');
    console.error('\n❌ Error:', err);
  } finally {
    await client.end();
    rl.close();
  }
}

main();
